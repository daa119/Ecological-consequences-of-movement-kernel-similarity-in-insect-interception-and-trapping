function figure_8()
% Capture, interception and edge leakage across panel sizes.
% Capture is estimated separately at per-contact adhesion probabilities of
% 0.1 and 0.5. The 0.5 batch also estimates interception (at least one
% finite-panel contact) and edge leakage (a plane crossing outside the
% panel before any contact). Both outcomes can occur on one trajectory.
%
% The Chi(3) scale is calibrated from nominal flight speed.
% The folded-Cauchy model has no finite mean step length. Until the first
% crossing of the panel plane, headings are biased toward an individually
% assigned target on the square panel. Later ordinary headings are isotropic.
% Capture simulations test the whole segment for panel contact before
% checking endpoint escape. After failed adhesion, the trajectory resumes
% from the contact point with a small offset and an outward heading.

clear;
clc;
close all;

rng(1);

save_figure = true;

%% ==========================================================
% SIMULATION SIZE
% ===========================================================

N = 10^3;          % trajectories per movement case and panel size

%% ==========================================================
% ECOLOGICAL MOVEMENT PARAMETERS
% ===========================================================

dt = 0.02;         % time step (s)

meanSpeed = 25;    % nominal short-distance flight speed (cm/s)

meanStep = ...
    meanSpeed * dt;

% For 3D Gaussian movement:
%
% E[l] = 4*sigma/sqrt(2*pi)

sigma = ...
    meanStep * sqrt(2*pi) / 4;

maxSteps = 1000;    % 20 s maximum duration

%% ==========================================================
% DIRECTIONAL BIAS
% ===========================================================

kappa_b = 0.3;  % Same pre-crossing vMF concentration as Figures 6 and 7.

%% ==========================================================
% LONG-DISTANCE MOVEMENT CASES
% ===========================================================

p_values = ...
    [0.1 0.5 0.650 0.9];

p_opt = 0.650;

gamma_values = ...
    zeros(size(p_values));

for ip = 1:length(p_values)

    p = ...
        p_values(ip);

    if abs(p-p_opt) < 1e-12

        % Stated optimal 3D relationship
        gamma_values(ip) = ...
            2.089 * sigma;

    else

        gamma_values(ip) = ...
            gamma_from_p_3d( ...
            p, ...
            sigma);

    end

end

%% ==========================================================
% GEOMETRY
% ===========================================================

xStart = -50;       % release plane (cm)

releaseRad = 10;    % release-disc radius (cm)

% Square panel side lengths
L_vals = ...
    2:2:30;

%% ==========================================================
% CONTACT MODEL
% ===========================================================

pStick_vals = ...
    [0.1 0.5];

kappa_post = 5.0;

epsShift = 1e-3;    % cm

%% ==========================================================
% ESCAPE DOMAIN
% ===========================================================

xEscapePos = 100;

xEscapeNeg = -100;

rEscape = 100;

%% ==========================================================
% DISPLAY PARAMETERS
% ===========================================================

fprintf('\n');
fprintf('Gaussian scale sigma = %.4f cm\n',sigma);
fprintf('Mean directional cosine = %.3f\n',1/tanh(kappa_b)-1/kappa_b);
fprintf('Directional concentration kappa_b = %.4f\n',kappa_b);
fprintf('\n');

for ip = 1:length(p_values)

    fprintf( ...
        'p = %.3f: gamma = %.4f cm, gamma/sigma = %.4f\n', ...
        p_values(ip), ...
        gamma_values(ip), ...
        gamma_values(ip)/sigma);

end

fprintf('\n');

%% ==========================================================
% STORAGE
% ===========================================================

nCases = ...
    1 + length(p_values);

nL = ...
    length(L_vals);

% Row 1 = Gaussian
% Rows 2-5 = folded-Cauchy p cases

captureProb_01 = ...
    zeros(nCases,nL);

captureProb_05 = ...
    zeros(nCases,nL);

encounterProb = ...
    zeros(nCases,nL);

leakProb = ...
    zeros(nCases,nL);

%% ==========================================================
% MAIN SIMULATION
% ===========================================================

for iL = 1:nL

    L = ...
        L_vals(iL);

    W = L;
    H = L;

    fprintf( ...
        'Running L = %.1f cm\n', ...
        L);

    %% ------------------------------------------------------
    % CASE 1: SHORT-DISTANCE GAUSSIAN
    % -------------------------------------------------------

    % pStick = 0.1
    nCapture_01 = 0;

    for n = 1:N

        [~,capFlag,~] = ...
            simulate_one_trajectory_outcomes( ...
            sigma, ...
            NaN, ...
            maxSteps, ...
            xStart, ...
            releaseRad, ...
            W, ...
            H, ...
            kappa_b, ...
            xEscapePos, ...
            xEscapeNeg, ...
            rEscape, ...
            pStick_vals(1), ...
            kappa_post, ...
            epsShift, ...
            false);

        nCapture_01 = ...
            nCapture_01 + capFlag;

    end

    captureProb_01(1,iL) = ...
        nCapture_01/N;

    % pStick = 0.5
    nCapture_05 = 0;
    nEncounter = 0;
    nLeak = 0;

    for n = 1:N

        [encFlag,capFlag,leakFlag] = ...
            simulate_one_trajectory_outcomes( ...
            sigma, ...
            NaN, ...
            maxSteps, ...
            xStart, ...
            releaseRad, ...
            W, ...
            H, ...
            kappa_b, ...
            xEscapePos, ...
            xEscapeNeg, ...
            rEscape, ...
            pStick_vals(2), ...
            kappa_post, ...
            epsShift, ...
            false);

        nCapture_05 = ...
            nCapture_05 + capFlag;

        nEncounter = ...
            nEncounter + encFlag;

        nLeak = ...
            nLeak + leakFlag;

    end

    captureProb_05(1,iL) = ...
        nCapture_05/N;

    encounterProb(1,iL) = ...
        nEncounter/N;

    leakProb(1,iL) = ...
        nLeak/N;

    %% ------------------------------------------------------
    % CASES 2-5: LONG-DISTANCE FOLDED-CAUCHY
    % -------------------------------------------------------

    for ip = 1:length(p_values)

        gamma = ...
            gamma_values(ip);

        % pStick = 0.1
        nCapture_01 = 0;

        for n = 1:N

            [~,capFlag,~] = ...
                simulate_one_trajectory_outcomes( ...
                sigma, ...
                gamma, ...
                maxSteps, ...
                xStart, ...
                releaseRad, ...
                W, ...
                H, ...
                kappa_b, ...
                xEscapePos, ...
                xEscapeNeg, ...
                rEscape, ...
                pStick_vals(1), ...
                kappa_post, ...
                epsShift, ...
                true);

            nCapture_01 = ...
                nCapture_01 + capFlag;

        end

        captureProb_01(ip+1,iL) = ...
            nCapture_01/N;

        % pStick = 0.5
        nCapture_05 = 0;
        nEncounter = 0;
        nLeak = 0;

        for n = 1:N

            [encFlag,capFlag,leakFlag] = ...
                simulate_one_trajectory_outcomes( ...
                sigma, ...
                gamma, ...
                maxSteps, ...
                xStart, ...
                releaseRad, ...
                W, ...
                H, ...
                kappa_b, ...
                xEscapePos, ...
                xEscapeNeg, ...
                rEscape, ...
                pStick_vals(2), ...
                kappa_post, ...
                epsShift, ...
                true);

            nCapture_05 = ...
                nCapture_05 + capFlag;

            nEncounter = ...
                nEncounter + encFlag;

            nLeak = ...
                nLeak + leakFlag;

        end

        captureProb_05(ip+1,iL) = ...
            nCapture_05/N;

        encounterProb(ip+1,iL) = ...
            nEncounter/N;

        leakProb(ip+1,iL) = ...
            nLeak/N;

    end

end

