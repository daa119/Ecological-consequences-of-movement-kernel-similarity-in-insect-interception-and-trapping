%    'Interpreter','tex', ...
%    'FontName','Arial', ...
%    'FontSize',16);

ylabel( ...
    'capture (%)', ...
    'FontName','Arial', ...
    'FontSize',16);

title( ...
    '(a) {\itp}_{stick} = 0.1', ...
    'Interpreter','tex', ...
    'FontName','Arial', ...
