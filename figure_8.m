%% =====================================================================
% SIMULATE ONE TRAJECTORY AND RETURN ALL THREE OUTCOMES
% =====================================================================

function [encountered,captured,edgeLeak] = ...
    simulate_one_trajectory_outcomes( ...
    sigma, ...
    gamma, ...
    maxSteps, ...
    xStart, ...
    releaseRad, ...
    W, ...
    H, ...
    kappa_b, ...
    xEscapePos, ...
    xEscapeNeg, ...
    rEscape, ...
    pStick, ...
    kappa_post, ...
    epsShift, ...
    useLevy)

%% ----------------------------------------------------------
% Initial position
% ----------------------------------------------------------

theta = ...
    2*pi*rand;

rr = ...
    releaseRad*sqrt(rand);

y0 = ...
    rr*cos(theta);

z0 = ...
    rr*sin(theta);

r = ...
    [xStart y0 z0];

%% ----------------------------------------------------------
% Fixed random target on panel
% ----------------------------------------------------------

yTar = ...
    -W/2 + W*rand;

zTar = ...
    -H/2 + H*rand;

pTar = ...
    [0 yTar zTar];

attractionOn = ...
    true;

%% ----------------------------------------------------------
% Outcome flags
% ----------------------------------------------------------

encountered = ...
    false;

captured = ...
    false;

edgeLeak = ...
    false;

% This flag distinguishes edge leakage on the initial
% approach from plane crossings occurring after a panel contact.

hadPanelContact = ...
    false;

%% ----------------------------------------------------------
% Movement loop
% ----------------------------------------------------------

for t = 1:maxSteps

    %% ------------------------------------------------------
    % DIRECTION
    % -------------------------------------------------------

    if attractionOn

        g = ...
            pTar-r;

        ng = ...
            norm(g);

        if ng < 1e-14

            g = ...
                [1 0 0];

        else

            g = ...
                g/ng;

        end

        v_new = ...
            sample_vMF_3d( ...
            g, ...
            kappa_b);

    else

        % No persistence and no bias after first interaction
        % with the panel plane.

        v_new = ...
            rand_unit_vector();

    end

    %% ------------------------------------------------------
    % STEP LENGTH
    % -------------------------------------------------------

    if useLevy

        ell = ...
            sample_folded_cauchy( ...
            gamma);

    else

        ell = ...
            sample_chi3( ...
            sigma);

    end

    %% ------------------------------------------------------
    % POSITION UPDATE
    % -------------------------------------------------------

    r_new = ...
        r + ell*v_new;

    %% ------------------------------------------------------
    % TEST INTERSECTION WITH PANEL PLANE
    % -------------------------------------------------------

    [isHit,crossedPlane,cp] = ...
        segment_hits_panel( ...
        r, ...
        r_new, ...
        W, ...
        H);

    %% ------------------------------------------------------
    % PANEL CONTACT
    % -------------------------------------------------------

    if isHit

        encountered = ...
            true;

        hadPanelContact = ...
            true;

        if rand < pStick

            captured = ...
                true;

            return;

        else

            % Failed capture:
            % move away from the panel using the same
            % post-contact rule as Figures 6 and 7.

            v_post = ...
                sample_post_contact_heading( ...
                kappa_post);

            if useLevy

                ell_post = ...
                    sample_folded_cauchy( ...
                    gamma);

            else

                ell_post = ...
                    sample_chi3( ...
                    sigma);

            end

            r = ...
                cp + ...
                epsShift*v_post;

            r_new2 = ...
                r + ...
                ell_post*v_post;

            if r_new2(1) > xEscapePos || ...
               r_new2(1) < xEscapeNeg || ...
               norm(r_new2) > rEscape

                return;

            end

            r = ...
                r_new2;

            attractionOn = ...
                false;

            continue;

        end

    %% ------------------------------------------------------
    % CROSS PANEL PLANE OUTSIDE FINITE PANEL
    % -------------------------------------------------------

    elseif crossedPlane

        % Edge leakage is defined as crossing x = 0 outside
        % the finite panel before any previous panel contact.

        if ~hadPanelContact

            edgeLeak = ...
                true;

        end

        % Keep the original endpoint and disable bias for future steps.
        attractionOn = false;

        if norm(r_new) > rEscape
            return;
        end

        r = r_new;
        continue;


    %% ------------------------------------------------------
    % ORDINARY MOVEMENT
    % -------------------------------------------------------

    else

        if r_new(1) > xEscapePos || ...
           r_new(1) < xEscapeNeg || ...
           norm(r_new) > rEscape

            return;

        end

        r = ...
            r_new;

    end

end

end

%% =====================================================================
% CHI(3) STEP LENGTH
% =====================================================================

function ell = ...
    sample_chi3( ...
    sigma)

ell = ...
    sigma * ...
    sqrt( ...
    randn^2 + ...
    randn^2 + ...
    randn^2);

end

%% =====================================================================
% FOLDED-CAUCHY STEP LENGTH
% =====================================================================

function ell = ...
    sample_folded_cauchy( ...
    gamma)

U = ...
    rand;

ell = ...
    gamma * ...
    tan((pi/2)*U);

end

%% =====================================================================
% CALCULATE CAUCHY SCALE FROM COMMON SURVIVAL PROBABILITY p
% =====================================================================

function gamma = ...
    gamma_from_p_3d( ...
    p, ...
    sigma)

% For a Chi(3) step-length distribution:
%
% P(l > L) =
%
% erfc(L/(sqrt(2)*sigma))
% + sqrt(2/pi)*(L/sigma)
%   exp[-L^2/(2*sigma^2)]
%
% Let q = L/sigma.
%
% For the folded-Cauchy distribution:
%
% P(l > L) =
%
% 1 - (2/pi)*atan(L/gamma).
%
% Equating the two survival probabilities at p gives
%
% gamma =
%
% L / tan[(pi/2)(1-p)].

f = ...
    @(q) ...
    erfc(q/sqrt(2)) + ...
    sqrt(2/pi)*q.*exp(-q.^2/2) - p;

q = ...
    fzero( ...
    f, ...
    [1e-10 20]);

Lmatch = ...
    q*sigma;

gamma = ...
    Lmatch / ...
    tan((pi/2)*(1-p));

end

%% =====================================================================
% POST-CONTACT HEADING
% =====================================================================

function v = ...
    sample_post_contact_heading( ...
    kappa_post)

mu_post = ...
    [-1 0 0];

while true

    v = ...
        sample_vMF_3d( ...
        mu_post, ...
        kappa_post);

    if v(1) < 0

        return;

    end

end

end

%% =====================================================================
% PANEL INTERSECTION
% =====================================================================

function [tf,crossedPlane,point] = ...
    segment_hits_panel( ...
    r1, ...
    r2, ...
    W, ...
    H)

x1 = ...
    r1(1);

x2 = ...
    r2(1);

crossedPlane = ...
    false;

point = ...
    [NaN NaN NaN];

if (x1 < 0 && x2 < 0) || ...
   (x1 > 0 && x2 > 0)

    tf = ...
        false;

    return;

end

dx = ...
    x2-x1;

if abs(dx) < 1e-14

    tf = ...
        false;

    return;

end

tau = ...
    -x1/dx;

if tau < 0 || tau > 1

    tf = ...
        false;

    return;

end

crossedPlane = ...
    true;

yint = ...
    r1(2) + ...
    tau*(r2(2)-r1(2));

zint = ...
    r1(3) + ...
    tau*(r2(3)-r1(3));

point = ...
    [0 yint zint];

tf = ...
    (abs(yint) <= W/2) && ...
    (abs(zint) <= H/2);

end

%% =====================================================================
% VON MISES-FISHER DIRECTION
% =====================================================================

function x = ...
    sample_vMF_3d( ...
    mu, ...
    kappa)

mu = ...
    mu(:)'/norm(mu);

if kappa < 1e-10

    x = ...
        rand_unit_vector();

    return;

end

u = ...
    rand;

a = ...
    exp(-kappa);

b = ...
    exp(kappa);

w = ...
    (1/kappa) * ...
    log(a + u*(b-a));

w = ...
    min(1,max(-1,w));

phi = ...
    2*pi*rand;

s = ...
    sqrt(max(0,1-w^2));

xp = ...
    [ ...
    s*cos(phi), ...
    s*sin(phi), ...
    w];

north = ...
    [0 0 1];

if norm(mu-north) < 1e-12

    x = ...
        xp;

elseif norm(mu+north) < 1e-12

    x = ...
        [xp(1) xp(2) -xp(3)];

else

    R = ...
        rotation_matrix_from_a_to_b( ...
        north, ...
        mu);

    x = ...
        (R*xp(:))';

    x = ...
        x/norm(x);

end

end

%% =====================================================================
% ROTATION MATRIX
% =====================================================================

function R = ...
    rotation_matrix_from_a_to_b( ...
    a, ...
    b)

a = ...
    a(:)/norm(a);

b = ...
    b(:)/norm(b);

v = ...
    cross(a,b);

s = ...
    norm(v);

c = ...
    dot(a,b);

if s < 1e-14

    if c > 0

        R = ...
            eye(3);

    else

        if abs(a(1)) < 0.9

            tmp = ...
                [1;0;0];

        else

            tmp = ...
                [0;1;0];

        end

        v = ...
            cross(a,tmp);

        v = ...
            v/norm(v);

        K = ...
            [ ...
             0    -v(3)  v(2); ...
             v(3)  0    -v(1); ...
            -v(2)  v(1)  0];

        R = ...
            eye(3) + ...
            2*K*K;

    end

    return;

end

K = ...
    [ ...
     0    -v(3)  v(2); ...
     v(3)  0    -v(1); ...
    -v(2)  v(1)  0];

R = ...
