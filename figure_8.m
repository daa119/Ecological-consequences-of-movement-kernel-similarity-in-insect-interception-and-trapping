subplot(2,2,2);

hold on;

for ic = 1:nCases

    plot( ...
        L_vals, ...
        100*captureProb_05(ic,:), ...
        'Color',lineColors(ic,:), ...
        'LineStyle',lineStyles{ic}, ...
        'LineWidth',lineWidth);

end

%xlabel( ...
%    'panel side length, {\itL} (cm)', ...
