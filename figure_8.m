%% ==========================================================
% PANEL (a): CAPTURE, pStick = 0.1
% ===========================================================

ax_capture_01 = subplot(2,2,1);

hold on;

for ic = 1:nCases

    hLeg(ic) = ...
        plot( ...
        L_vals, ...
